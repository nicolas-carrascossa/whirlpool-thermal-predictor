"""Loading of the three dataset-derived JSON files shared with the front-end.

The files live in `src/frontend/src/data/` (generated by
`scripts/build_registry.py`) and are read from disk — never copied — so that
front-end mock and back-end mock can never drift apart.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any

from app.config import get_settings

#: The 7 config columns, in the canonical order used for hashing/validation.
CONFIG_FIELDS: tuple[str, ...] = (
    "blower_direction",
    "housing",
    "board_position",
    "run_case",
    "losses",
    "deflector_hole",
    "material_coil_support",
)

#: The 5 variables the model (mock and real) actually uses.
MODEL_FIELDS: tuple[str, ...] = (
    "blower_direction",
    "housing",
    "run_case",
    "deflector_hole",
    "material_coil_support",
)

#: Accepted by the contract but deliberately outside the model (H2).
IGNORED_FIELDS: tuple[str, ...] = ("losses", "board_position")


@dataclass(frozen=True)
class Dataset:
    """Everything the predictors and the metadata endpoint need."""

    sensors: list[dict[str, Any]]
    per_sensor: dict[str, dict[str, Any]]
    run_configs: list[dict[str, Any]]
    variable_options: dict[str, dict[str, Any]]

    @property
    def key_areas(self) -> list[str]:
        """Key areas in first-appearance order of the tc_number-sorted list."""
        seen: list[str] = []
        for sensor in self.sensors:
            if sensor["key_area"] not in seen:
                seen.append(sensor["key_area"])
        return seen

    def options_for(self, field: str) -> list[str]:
        return list(self.variable_options.get(field, {}).get("options", []))


def _read_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


@lru_cache
def load_dataset() -> Dataset:
    data_dir = get_settings().data_dir
    registry = _read_json(data_dir / "sensor_registry.json")
    stats = _read_json(data_dir / "sensor_stats.json")
    options = _read_json(data_dir / "variable_options.json")

    # Stable sensor order: guarantees the mock noise stream does not depend on
    # the target filter (same rule as LocalMockSource.SENSOR_ORDER).
    sensors = sorted(registry, key=lambda s: s["tc_number"])

    return Dataset(
        sensors=sensors,
        per_sensor=stats["per_sensor"],
        run_configs=stats["run_configs"],
        variable_options=options,
    )
