"""Loading of the dataset-derived JSON files shared with the front-end.

The files live in `src/frontend/src/data/` (generated by
`scripts/build_registry.py` and `scripts/export_models.py`) and are read from
disk — never copied — so that front-end mock and back-end mock can never drift
apart.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any

from app.config import get_settings

#: The 7 config columns, in the canonical order used for hashing/validation.
CONFIG_FIELDS: tuple[str, ...] = (
    "blower_direction",
    "housing",
    "board_position",
    "run_case",
    "losses",
    "deflector_hole",
    "material_coil_support",
)

#: The 5 variables the model (mock and real) actually uses.
MODEL_FIELDS: tuple[str, ...] = (
    "blower_direction",
    "housing",
    "run_case",
    "deflector_hole",
    "material_coil_support",
)

#: Accepted by the contract but deliberately outside the model (H2).
IGNORED_FIELDS: tuple[str, ...] = ("losses", "board_position")

#: Fallback used only when `model_manifest.json` is absent (fresh clone before
#: `scripts/export_models.py` ran). Keeps the mock working; the real predictor
#: refuses to start without the manifest.
_FALLBACK_AREA_ALGORITHMS: dict[str, str] = {
    "Mainback": "random_forest",
    "IPC Comp": "random_forest",
    "IPC Cooling": "random_forest",
    "Coil Temps": "gradient_boosting",
    "CT Knobs": "gradient_boosting",
    "Main Vent Sys": "gradient_boosting",
    "Oven HMI": "gradient_boosting",
}

ALGORITHM_LABELS: dict[str, str] = {
    "random_forest": "Random Forest",
    "gradient_boosting": "Gradient Boosting",
}


@dataclass(frozen=True)
class Dataset:
    """Everything the predictors and the metadata endpoint need."""

    sensors: list[dict[str, Any]]
    per_sensor: dict[str, dict[str, Any]]
    run_configs: list[dict[str, Any]]
    variable_options: dict[str, dict[str, Any]]
    #: key_area -> algorithm, straight from the model manifest (v1.1). The
    #: mapping is configuration, never code: changing it is a re-export, not a
    #: deploy.
    area_algorithms: dict[str, str]
    #: Per-algorithm metadata from the manifest (version, training date).
    algorithms: dict[str, dict[str, Any]]
    #: Validation metrics by area, for `GET /api/v1/metrics`.
    metrics_by_area: dict[str, dict[str, Any]]
    #: Version of the artifact SET, or the mock's own version.
    model_set_version: str

    @property
    def key_areas(self) -> list[str]:
        """Key areas in first-appearance order of the tc_number-sorted list."""
        seen: list[str] = []
        for sensor in self.sensors:
            if sensor["key_area"] not in seen:
                seen.append(sensor["key_area"])
        return seen

    def options_for(self, field: str) -> list[str]:
        return list(self.variable_options.get(field, {}).get("options", []))

    def algorithm_for(self, key_area: str) -> str:
        """Algorithm serving an area. Unknown area falls back to random_forest."""
        return self.area_algorithms.get(key_area, "random_forest")


def _read_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


@lru_cache
def load_dataset() -> Dataset:
    data_dir = get_settings().data_dir
    registry = _read_json(data_dir / "sensor_registry.json")
    stats = _read_json(data_dir / "sensor_stats.json")
    options = _read_json(data_dir / "variable_options.json")

    manifest_path = data_dir / "model_manifest.json"
    manifest: dict[str, Any] = (
        _read_json(manifest_path) if manifest_path.exists() else {}
    )

    # Stable sensor order: guarantees the mock noise stream does not depend on
    # the target filter (same rule as LocalMockSource.SENSOR_ORDER).
    sensors = sorted(registry, key=lambda s: s["tc_number"])

    return Dataset(
        sensors=sensors,
        per_sensor=stats["per_sensor"],
        run_configs=stats["run_configs"],
        variable_options=options,
        area_algorithms=dict(manifest.get("area_algorithms") or _FALLBACK_AREA_ALGORITHMS),
        algorithms=dict(manifest.get("algorithms") or {}),
        metrics_by_area=dict(manifest.get("metrics_by_area") or {}),
        model_set_version=str(manifest.get("model_set_version") or "models-dev"),
    )
